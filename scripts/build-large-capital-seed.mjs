async function fetchNav(code, startValue, endValue) {
  const fetchPage = async (pageIndex) => {
    const url = new URL('https://api.fund.eastmoney.com/f10/lsjz');
    Object.entries({ fundCode: code, pageIndex: String(pageIndex), pageSize: '20', startDate: startValue, endDate: endValue, _: String(Date.now()) }).forEach(([key, value]) => url.searchParams.set(key, value));
    return fetchJson(url, { referer: `https://fundf10.eastmoney.com/jjjz_${code}.html` });
  };
  const first = await fetchPage(1);
  const pageCount = Math.ceil(Number(first.TotalCount ?? 0) / 20);
  const rest = pageCount > 1 ? await mapLimit(Array.from({ length: pageCount - 1 }, (_, index) => index + 2), 3, fetchPage) : [];
  return [first, ...rest].flatMap((payload) => payload.Data?.LSJZList ?? []).map((row) => ({ date: row.FSRQ, nav: finite(row.DWJZ) })).filter((row) => row.date && row.nav !== null).sort(byDate);
}

async function fetchSseShares(dates) {
  const codes = new Set(LARGE_CAPITAL_ETFS.filter((item) => item.exchange === 'SSE').map((item) => item.code));
  const result = new Map([...codes].map((code) => [code, new Map(previousEtfSeries(code, (point) => [point.date, point.shares]).filter(([, shares]) => Number(shares) > 0))]));
  await mapLimit(dates, 6, async (date) => {
    try {
      const url = new URL('https://query.sse.com.cn/commonQuery.do');
      Object.entries({ isPagination: 'true', 'pageHelp.pageSize': '10000', 'pageHelp.pageNo': '1', 'pageHelp.beginPage': '1', 'pageHelp.cacheSize': '1', 'pageHelp.endPage': '1', sqlId: 'COMMON_SSE_ZQPZ_ETFZL_XXPL_ETFGM_SEARCH_L', STAT_DATE: date }).forEach(([key, value]) => url.searchParams.set(key, value));
      const payload = await fetchJson(url, { referer: 'https://www.sse.com.cn/' });
      for (const row of payload.result ?? payload.pageHelp?.data ?? []) {
        if (codes.has(row.SEC_CODE) && finite(row.TOT_VOL) > 0) result.get(row.SEC_CODE).set(date, finite(row.TOT_VOL) * 10000);
      }
    } catch (error) { console.warn(`SSE shares ${date}: ${error instanceof Error ? error.message : error}`); }
  });
  return result;
}

async function fetchSzseShares(firstDate, lastDate) {
  const codes = new Set(LARGE_CAPITAL_ETFS.filter((item) => item.exchange === 'SZSE').map((item) => item.code));
  const result = new Map([...codes].map((code) => [code, new Map(previousEtfSeries(code, (point) => [point.date, point.shares]).filter(([, shares]) => Number(shares) > 0))]));
  for (const [chunkStart, chunkEnd] of dateChunks(firstDate, lastDate, 175)) {
    try {
      const url = new URL('https://www.szse.cn/api/report/ShowReport');
      Object.entries({ SHOWTYPE: 'xlsx', CATALOGID: 'scsj_fund_jjgm', TABKEY: 'tab1', txtStart: chunkStart, txtEnd: chunkEnd, jjlb: 'ETF', random: String(Math.random()) }).forEach(([key, value]) => url.searchParams.set(key, value));
      const response = await fetchWithRetry(url, { headers: requestHeaders('https://www.szse.cn/market/fund/volume/etf/index.html') });
      const workbook = new ExcelJS.Workbook();
      await workbook.xlsx.load(await response.arrayBuffer());
      const sheet = workbook.worksheets[0];
      sheet.eachRow((row, number) => {
        if (number === 1) return;
        const date = normalizeExcelDate(row.getCell(1).value);
        const code = String(row.getCell(2).text ?? '').trim().padStart(6, '0');
        const shares = finite(String(row.getCell(4).text ?? '').replaceAll(',', ''));
        if (date && codes.has(code) && shares > 0) result.get(code).set(date, shares);
      });
    } catch (error) { console.warn(`SZSE shares ${chunkStart}..${chunkEnd}: ${error instanceof Error ? error.message : error}`); }
  }
  return result;
}

async function fetchAmounts(code, limit) {
  const url = new URL('https://push2his.eastmoney.com/api/qt/stock/kline/get');
  const secid = /^[569]/.test(code) ? `1.${code}` : `0.${code}`;
  Object.entries({ secid, klt: '101', fqt: '1', lmt: String(limit), end: '20500101', iscca: '1', fields1: 'f1,f2,f3,f4,f5,f6', fields2: 'f51,f52,f53,f54,f55,f56,f57,f58' }).forEach(([key, value]) => url.searchParams.set(key, value));
  const payload = await fetchJson(url);
  return new Map((payload.data?.klines ?? []).map((line) => {
    const columns = line.split(',');
    return [columns[0], finite(columns[6])];
  }));
}

async function fetchBenchmark(secid, limit) {
  const url = new URL('https://push2his.eastmoney.com/api/qt/stock/kline/get');
  Object.entries({ secid, klt: '101', fqt: '1', lmt: String(limit), end: '20500101', iscca: '1', fields1: 'f1,f2,f3,f4,f5,f6', fields2: 'f51,f52,f53,f54,f55,f56,f57,f58' }).forEach(([key, value]) => url.searchParams.set(key, value));
  const payload = await fetchJson(url);
  return (payload.data?.klines ?? []).map((line) => {
    const columns = line.split(',');
    return { date: columns[0], close: finite(columns[2]) };
  }).filter((point) => point.close !== null);
}

async function fetchCffexDay({ date, product }) {
  const compact = date.replaceAll('-', '');
  const url = `http://www.cffex.com.cn/sj/ccpm/${compact.slice(0, 6)}/${compact.slice(6)}/${product}_1.csv`;
  try {
    const response = await fetchWithRetry(url, { headers: requestHeaders('http://www.cffex.com.cn/') }, 2);
    const text = new TextDecoder('gbk').decode(await response.arrayBuffer());
    const rows = parseCffexCsv(text, product);
    return rows.length ? aggregateCffexDay(rows, product, date) : null;
  } catch (error) {
    if (String(error).includes('404')) return null;
    console.warn(`CFFEX ${product} ${date}: ${error instanceof Error ? error.message : error}`);
    return null;
  }
}

async function fetchJson(url, { referer } = {}) {
  const response = await fetchWithRetry(url, { headers: requestHeaders(referer) });
  return response.json();
}

async function fetchWithRetry(url, init = {}, attempts = 3) {
  let lastError;
  for (let attempt = 1; attempt <= attempts; attempt += 1) {
    try {
      const response = await fetch(url, { ...init, signal: AbortSignal.timeout(20000) });
      if (!response.ok) throw new Error(`HTTP ${response.status} ${url}`);
      return response;
    } catch (error) {
      lastError = error;
      if (attempt < attempts) await new Promise((resolve) => setTimeout(resolve, attempt * 350));
    }
  }
  throw lastError;
}

async function mapLimit(items, concurrency, mapper) {
  const output = new Array(items.length);
  let cursor = 0;
  async function worker() {
    while (cursor < items.length) {
      const index = cursor;
      cursor += 1;
      output[index] = await mapper(items[index], index);
    }
  }
  await Promise.all(Array.from({ length: Math.min(concurrency, items.length) }, worker));
  return output;
}

async function safeSource(label, task, fallback) {
  try { return await task(); }
  catch (error) { console.warn(`${label}: ${error instanceof Error ? error.message : error}`); return fallback; }
}

function previousEtfSeries(code, mapper) {
  return (previousEtfByCode.get(code)?.series ?? []).map(mapper).filter((value) => Array.isArray(value) ? value[1] !== null : value.nav !== null);
}

function requestHeaders(referer) { return { 'user-agent': USER_AGENT, ...(referer ? { referer } : {}) }; }
function finite(value) { const parsed = Number(value); return Number.isFinite(parsed) ? parsed : null; }
function isoDate(date) { return date.toISOString().slice(0, 10); }
function byDate(a, b) { return a.date.localeCompare(b.date); }
function normalizeExcelDate(value) { return value instanceof Date ? isoDate(value) : String(value ?? '').slice(0, 10); }

function dateChunks(startValue, endValue, days) {
  const chunks = [];
  let cursor = new Date(`${startValue}T00:00:00Z`);
  const endValueDate = new Date(`${endValue}T00:00:00Z`);
  while (cursor <= endValueDate) {
    const chunkEnd = new Date(Math.min(endValueDate.getTime(), cursor.getTime() + (days - 1) * 86400000));
    chunks.push([isoDate(cursor), isoDate(chunkEnd)]);
    cursor = new Date(chunkEnd.getTime() + 86400000);
  }
  return chunks;
}
