import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const EASTMONEY_TOKEN = 'bd1d9ddb04089700cf9c27f6f7426281';
const UNIVERSE = 'm:0+t:6,m:0+t:80,m:1+t:2,m:1+t:23,m:0+t:81+s:2048';
const TARGET_DAYS = 252;
const HISTORY_DAYS = 285;
const CONCURRENCY = 24;
const MINIMUM_COVERAGE = 0.8;

console.log('loading index history');
const indexHistory = await fetchIndexHistory();
const targetDates = indexHistory.map((row) => row.date).sort().slice(-TARGET_DAYS);
const targetSet = new Set(targetDates);
console.log('loading stock universe');
const metadata = await fetchStockUniverse();
const aggregates = new Map(targetDates.map((date) => [date, createAggregate()]));

let completed = 0;
await concurrentMap(metadata, CONCURRENCY, async (stock) => {
  const rows = await fetchStockHistory(stock.code);
  for (let index = 0; index < rows.length; index += 1) {
    const row = rows[index];
    if (!targetSet.has(row.date)) continue;
    const aggregate = aggregates.get(row.date);
    if (Number.isFinite(row.turnover) && Number.isFinite(stock.freeMarketCap) && stock.freeMarketCap > 0) {
      aggregate.turnoverWeighted += row.turnover * stock.freeMarketCap;
      aggregate.turnoverWeight += stock.freeMarketCap;
    }
    if (Number.isFinite(row.amount) && row.amount >= 0) {
      aggregate.totalAmount += row.amount;
      if (stock.industry) aggregate.industryAmounts.set(stock.industry, (aggregate.industryAmounts.get(stock.industry) ?? 0) + row.amount);
    }
    if (Number.isFinite(row.changePercent)) {
      aggregate.risingValid += 1;
      if (row.changePercent > 0) {
        aggregate.rising += 1;
        if (row.changePercent <= 5) aggregate.rising0To5 += 1;
        else if (row.changePercent <= 10) aggregate.rising5To10 += 1;
        else aggregate.risingAbove10 += 1;
      }
    }
    if (index >= 19 && Number.isFinite(row.close)) {
      const window = rows.slice(index - 19, index + 1).map((item) => item.close);
      if (window.length === 20 && window.every(Number.isFinite)) {
        aggregate.ma20Valid += 1;
        if (row.close > window.reduce((sum, value) => sum + value, 0) / 20) aggregate.aboveMa20 += 1;
      }
    }
  }
  completed += 1;
  if (completed % 500 === 0 || completed === metadata.length) console.log(`stock history ${completed}/${metadata.length}`);
});

const minimumDailyStocks = Math.floor(metadata.length * MINIMUM_COVERAGE);
for (const [date, aggregate] of aggregates) {
  if (aggregate.risingValid < minimumDailyStocks || aggregate.industryAmounts.size < 20) {
    throw new Error(`insufficient stock coverage on ${date}: ${aggregate.risingValid}/${metadata.length} stocks, ${aggregate.industryAmounts.size} industries`);
  }
}

const [marginRows, yieldRows, indexMeta] = await Promise.all([fetchMarginHistory(), fetchYieldHistory(targetDates[0], targetDates.at(-1)), fetchIndexMeta()]);
const marginByDate = new Map(marginRows.map((row) => [row.date, row]));
const yieldByDate = new Map(yieldRows.map((row) => [row.date, row.tenYear]));
const indexByDate = new Map(indexHistory.map((row) => [row.date, row]));
const currentIndex = indexHistory.at(-1);

const seedRows = targetDates.map((date) => {
  const aggregate = aggregates.get(date);
  const index = indexByDate.get(date);
  const margin = marginByDate.get(date);
  const yield10y = nearestOnOrBefore(yieldByDate, date);
  const estimatedPe = indexMeta.peDynamic * (index.close / currentIndex.close);
  const topIndustryEntries = [...aggregate.industryAmounts.entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, 3);
  const top3Amount = topIndustryEntries.reduce((sum, [, amount]) => sum + amount, 0);
  const top3Industries = topIndustryEntries
    .map(([name, amount]) => ({ name, amountYi: round(amount / 100_000_000, 2), share: round((amount / aggregate.totalAmount) * 100, 2) }));
  return {
    date,
    turnover: round(aggregate.turnoverWeighted / aggregate.turnoverWeight, 4),
    top3IndustryShare: round((top3Amount / aggregate.totalAmount) * 100, 4),
    top3Industries,
    totalAmountYi: round(aggregate.totalAmount / 100_000_000, 2),
    risingShare: round((aggregate.rising / aggregate.risingValid) * 100, 4),
    rising0To5Share: round((aggregate.rising0To5 / aggregate.risingValid) * 100, 4),
    rising5To10Share: round((aggregate.rising5To10 / aggregate.risingValid) * 100, 4),
    risingAbove10Share: round((aggregate.risingAbove10 / aggregate.risingValid) * 100, 4),
    aboveMa20Share: round((aggregate.aboveMa20 / aggregate.ma20Valid) * 100, 4),
    marginBuyShare: round((margin.rzmre / (index.amountYi * 100_000_000)) * 100, 4),
    erp: round((100 / estimatedPe) - yield10y, 4),
  };
}).filter((row) => ['turnover', 'top3IndustryShare', 'totalAmountYi', 'risingShare', 'rising0To5Share', 'rising5To10Share', 'risingAbove10Share', 'aboveMa20Share', 'marginBuyShare', 'erp'].every((key) => Number.isFinite(row[key])));

const output = `// Generated by scripts/build-sentiment-seed.mjs from public market sources.\nexport const SENTIMENT_SEED_ROWS = ${JSON.stringify(seedRows)};\nexport const SENTIMENT_SEED_META = ${JSON.stringify({ generatedAt: new Date().toISOString(), universeSize: metadata.length, commonAsOf: seedRows.at(-1)?.date, note: '公开数据代理口径；历史 ERP 使用国证A指点位比例回推市盈率。' })};\n`;
await writeFile(resolve('server/sentiment-seed.mjs'), output, 'utf8');
console.log(`wrote ${seedRows.length} rows to server/sentiment-seed.mjs`);

function createAggregate() {
  return { turnoverWeighted: 0, turnoverWeight: 0, totalAmount: 0, industryAmounts: new Map(), rising: 0, rising0To5: 0, rising5To10: 0, risingAbove10: 0, risingValid: 0, aboveMa20: 0, ma20Valid: 0 };
}

async function fetchStockUniverse() {
  const first = await fetchStockPage(1);
  const pages = Math.ceil(first.total / 100);
  const rest = await concurrentMap(Array.from({ length: pages - 1 }, (_, index) => index + 2), 3, fetchStockPage);
  return [first, ...rest]
    .flatMap((page) => page.rows)
    .filter((row) => /^\d{6}$/.test(String(row.f12)) && !/ST|退/.test(String(row.f14 ?? '')))
    .map((row) => ({ code: String(row.f12), industry: String(row.f100 ?? '').trim(), freeMarketCap: number(row.f21) }));
}

async function fetchStockPage(page) {
  const url = new URL('https://push2delay.eastmoney.com/api/qt/clist/get');
  setParams(url, { pn: page, pz: 100, po: 1, np: 1, ut: EASTMONEY_TOKEN, fltt: 2, invt: 2, fid: 'f20', fs: UNIVERSE, fields: 'f12,f14,f21,f100' });
  const payload = await fetchJson(url, 5);
  return { total: payload.data?.total ?? 0, rows: payload.data?.diff ?? [] };
}

async function fetchStockHistory(code) {
  const url = new URL('https://push2his.eastmoney.com/api/qt/stock/kline/get');
  setParams(url, { secid: `${/^[659]/.test(code) ? 1 : 0}.${code}`, ut: EASTMONEY_TOKEN, klt: 101, fqt: 0, lmt: HISTORY_DAYS, end: '20500101', fields1: 'f1,f2,f3,f4,f5,f6', fields2: 'f51,f52,f53,f54,f55,f56,f57,f58,f59,f60,f61' });
  const payload = await fetchJson(url, 3).catch(() => ({}));
  return (payload.data?.klines ?? []).map((line) => {
    const values = line.split(',');
    return { date: values[0], close: number(values[2]), amount: number(values[6]), changePercent: number(values[8]), turnover: number(values[10]) };
  });
}

async function fetchIndexHistory() {
  const end = new Date().toISOString().slice(0, 10);
  const startDate = new Date(); startDate.setUTCFullYear(startDate.getUTCFullYear() - 2);
  const url = new URL('https://hq.cnindex.com.cn/market/market/getIndexDailyDataWithDataFormat');
  setParams(url, { indexCode: '399317', startDate: startDate.toISOString().slice(0, 10), endDate: end, frequency: 'day' });
  const payload = await fetchJson(url);
  return (payload.data?.data ?? []).map((row) => ({ date: row[0], close: number(row[5]), amountYi: number(row[8]) })).sort((a, b) => a.date.localeCompare(b.date));
}

async function fetchIndexMeta() {
  const payload = await fetchJson('https://www.cnindex.com.cn/index/indexList?channelCode=205&rows=20&pageNum=1');
  const row = payload.data?.rows?.find((item) => item.indexcode === '399317');
  if (!Number.isFinite(number(row?.peDynamic))) throw new Error('CNI A-share PE unavailable');
  return { peDynamic: number(row.peDynamic) };
}

async function fetchMarginHistory() {
  const url = new URL('https://datacenter-web.eastmoney.com/api/data/v1/get');
  setParams(url, { reportName: 'RPTA_RZRQ_LSHJ', columns: 'DIM_DATE,RZMRE', source: 'WEB', pageNumber: 1, pageSize: 500, sortColumns: 'dim_date', sortTypes: -1 });
  const payload = await fetchJson(url);
  return (payload.result?.data ?? []).map((row) => ({ date: String(row.DIM_DATE).slice(0, 10), rzmre: number(row.RZMRE) }));
}

async function fetchYieldHistory(startDate, endDate) {
  const rows = [];
  for (let page = 1; page <= 3; page += 1) {
    const url = new URL('https://datacenter.eastmoney.com/api/data/get');
    setParams(url, { type: 'RPTA_WEB_TREASURYYIELD', sty: 'ALL', st: 'SOLAR_DATE', sr: -1, token: '894050c76af8597a853f5b408b759f5d', p: page, ps: 500, pageNo: page, pageNum: page });
    const payload = await fetchJson(url);
    const pageRows = payload.result?.data ?? [];
    rows.push(...pageRows);
    if (pageRows.some((row) => String(row.SOLAR_DATE).slice(0, 10) <= startDate) || pageRows.length < 500) break;
  }
  return rows
    .map((row) => ({ date: String(row.SOLAR_DATE).slice(0, 10), tenYear: number(row.EMM00166466) }))
    .filter((row) => row.date >= startDate && row.date <= endDate && Number.isFinite(row.tenYear));
}

function nearestOnOrBefore(map, date) {
  const key = [...map.keys()].filter((item) => item <= date).sort().at(-1);
  return key ? map.get(key) : null;
}

async function fetchJson(input, retries = 1) {
  let lastError;
  for (let attempt = 0; attempt <= retries; attempt += 1) {
    try {
      const response = await fetch(input, { signal: AbortSignal.timeout(10_000), headers: { 'User-Agent': 'Mozilla/5.0', Referer: 'https://data.eastmoney.com/' } });
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      return await response.json();
    } catch (error) {
      lastError = error;
      if (attempt < retries) await new Promise((resolveDelay) => setTimeout(resolveDelay, 250 * (attempt + 1)));
    }
  }
  throw lastError;
}

async function concurrentMap(items, concurrency, mapper) {
  const results = new Array(items.length);
  let next = 0;
  async function worker() {
    while (next < items.length) {
      const index = next; next += 1;
      results[index] = await mapper(items[index], index);
    }
  }
  await Promise.all(Array.from({ length: Math.min(concurrency, items.length) }, worker));
  return results;
}

function setParams(url, values) { Object.entries(values).forEach(([key, value]) => url.searchParams.set(key, String(value))); }
function number(value) { const parsed = Number(value); return Number.isFinite(parsed) ? parsed : null; }
function round(value, digits) { if (!Number.isFinite(value)) return null; const factor = 10 ** digits; return Math.round(value * factor) / factor; }
